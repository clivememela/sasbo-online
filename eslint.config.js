/**
 * 🔴 `no-unused-vars` CANNOT SEE A JSX ELEMENT REFERENCE, AND WITHOUT THIS IT REPORTS A USED
 * COMPONENT AND A DEAD ONE IDENTICALLY.
 *
 * ESLint's scope analysis has no idea that `<Icon />` reads the binding `Icon`. The core rule
 * therefore calls every JSX-only reference unused. MEASURED, on this config, 2026-09-10 --
 * three shapes of the same destructured param:
 *
 *   ({ icon: Icon }) => <Icon />          -> WARNED   (false positive: it is used)
 *   ({ icon: Icon }) => {String(Icon)}    -> clean    (an ordinary expression, so scope sees it)
 *   ({ icon: Icon }) => <span/>           -> WARNED   (true positive: it really is unused)
 *
 * The first and third are INDISTINGUISHABLE in the report, which is what makes this
 * load-bearing rather than untidy: `10.4` flips this repository to a hard 0 errors / 0
 * warnings, so left alone it makes correct code permanently unlintable, and the only way past
 * it is to delete the binding the JSX depends on. `About.jsx:213` was the live instance.
 *
 * 🔑 AND IT EXPLAINED THE `varsIgnorePattern: '^[A-Z_]'` THIS CONFIG USED TO CARRY, which was
 * never a style choice -- it was the workaround this blindness forces. Every component import
 * is PascalCase and used only in JSX, so without the pattern the rule flagged all of them;
 * with it, a genuinely dead component import was silently exempt. The rule was blind in both
 * directions at once, and the exemption is what made the second direction invisible.
 *
 * 🔬 SO THE PATTERN IS GONE, AND IT HAD BEEN HIDING EIGHTEEN DEAD BINDINGS. Measured 2026-09-10
 * by removing it: `Maintenance.jsx` imported **ten** icons used nowhere but inside its own
 * commented-out card blocks, three archive pages each imported `Search` and `X` and rendered
 * neither, `Header.jsx` still imported the `Logo` that `04.1` took out of it, and
 * `CaptureMember.jsx` imported `React` it never names. ⚠️ **A grep found each of the ten
 * `Maintenance` icons twice and called them live** -- the second hit was the comment. Same
 * instrument failure as F-P29: a scan that reads its own comments as code. eslint reads code.
 *
 * This is the same species as F-D12 -- a config manufacturing its own findings -- so it is
 * fixed the way that one was: at config level, deriving nothing and stating why.
 *
 * WHY A LOCAL RULE AND NOT `eslint-plugin-react`. The plugin's `jsx-uses-vars` is the
 * canonical fix and is fifteen lines of it. This repository is the incumbent developer's, a
 * dependency is a change to their tree, and the whole of what is needed is below. It is not
 * trusted on sight either: `src/test/eslintJsxUsage.test.js` runs ESLint over all three shapes
 * above and asserts the first is clean AND the third still warns -- so a rule that stopped
 * working, or one that suppressed everything, both go red (contract ⑪).
 */
const jsxUsage = {
  rules: {
    'jsx-uses-vars': {
      meta: { docs: { description: 'Mark a variable referenced by a JSX element as used.' } },
      create(context) {
        const sourceCode = context.sourceCode ?? context.getSourceCode()
        return {
          JSXOpeningElement(node) {
            // `<Foo>` is a JSXIdentifier; `<Foo.Bar>` and `<a.b.c>` nest inside
            // JSXMemberExpression, where only the leftmost object is a binding.
            let name = node.name
            while (name.type === 'JSXMemberExpression') name = name.object
            // A namespaced element (`<svg:rect>`) references no binding at all.
            if (name.type !== 'JSXIdentifier') return
            // A lowercase tag is an intrinsic element (`<div>`), never a binding.
            if (!/^[A-Z_$]/.test(name.name)) return
            sourceCode.markVariableAsUsed(name.name, node)
          },
        }
      },
    },
  },
}

